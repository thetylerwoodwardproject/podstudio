// Drizzle schema (SQLite via better-sqlite3), subset of BUILD_PLAN.md §4 needed for
// tonight's shell: users, shows, people, episodes, episode_people. Later stages add
// the remaining tables (projects, assets, recordings, feed_revisions, jobs, ...) as
// their stage starts, per BUILD_PLAN §4's own instruction not to introduce them all
// in Foundation.
//
// Conventions: ids are text UUIDv4, timestamps are integer unix-ms, booleans are
// integer 0/1, JSON blobs are stored as text.
import { sql, relations } from "drizzle-orm";
import {
  sqliteTable,
  text,
  integer,
  uniqueIndex,
  index,
  primaryKey,
} from "drizzle-orm/sqlite-core";

// users/sessions/accounts/verifications: generated by `@better-auth/cli generate`
// against apps/web/app/lib/auth.server.ts (drizzleAdapter, usePlural: true, plus the
// `role` additionalField) and merged in here by hand — see that file's comment.
// Better Auth owns these tables; don't hand-edit column shapes without regenerating,
// or its adapter and this schema will silently drift.
export const users = sqliteTable("users", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: integer("email_verified", { mode: "boolean" })
    .default(false)
    .notNull(),
  image: text("image"),
  createdAt: integer("created_at", { mode: "timestamp_ms" })
    .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
    .notNull(),
  updatedAt: integer("updated_at", { mode: "timestamp_ms" })
    .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
    .$onUpdate(() => new Date())
    .notNull(),
  role: text("role", { enum: ["admin", "editor"] }).default("editor"),
});

export const sessions = sqliteTable(
  "sessions",
  {
    id: text("id").primaryKey(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    token: text("token").notNull().unique(),
    createdAt: integer("created_at", { mode: "timestamp_ms" })
      .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
      .notNull(),
    updatedAt: integer("updated_at", { mode: "timestamp_ms" })
      .$onUpdate(() => new Date())
      .notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
  },
  (table) => [index("sessions_userId_idx").on(table.userId)],
);

export const accounts = sqliteTable(
  "accounts",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: integer("access_token_expires_at", {
      mode: "timestamp_ms",
    }),
    refreshTokenExpiresAt: integer("refresh_token_expires_at", {
      mode: "timestamp_ms",
    }),
    scope: text("scope"),
    password: text("password"),
    createdAt: integer("created_at", { mode: "timestamp_ms" })
      .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
      .notNull(),
    updatedAt: integer("updated_at", { mode: "timestamp_ms" })
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("accounts_userId_idx").on(table.userId)],
);

export const verifications = sqliteTable(
  "verifications",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    createdAt: integer("created_at", { mode: "timestamp_ms" })
      .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
      .notNull(),
    updatedAt: integer("updated_at", { mode: "timestamp_ms" })
      .default(sql`(cast(unixepoch('subsecond') * 1000 as integer))`)
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("verifications_identifier_idx").on(table.identifier)],
);

export const usersRelations = relations(users, ({ many }) => ({
  sessions: many(sessions),
  accounts: many(accounts),
}));

export const sessionsRelations = relations(sessions, ({ one }) => ({
  users: one(users, { fields: [sessions.userId], references: [users.id] }),
}));

export const accountsRelations = relations(accounts, ({ one }) => ({
  users: one(users, { fields: [accounts.userId], references: [users.id] }),
}));

export const shows = sqliteTable("shows", {
  id: text("id").primaryKey(),
  slug: text("slug").notNull().unique(),
  title: text("title").notNull(),
  // Immutable once set — enforce with a BEFORE UPDATE trigger in a later migration
  // once imports (Stage 06) can actually populate/compare it.
  podcastGuid: text("podcast_guid").notNull().unique(),
  feedUrl: text("feed_url"),
  locked: integer("locked").notNull().default(0),
  unlockedUntil: integer("unlocked_until"),
  website: text("website"),
  ownerEmail: text("owner_email").notNull(),
  timezone: text("timezone").notNull().default("UTC"),
  // Core RSS 2.0 / iTunes fields — added for screen 16 (Show tags). Podcasting 2.0
  // extension tags that don't need their own columns yet (funding, value, medium,
  // trailer, updateFrequency, license) live in `podcastTags` json below. `person`
  // belongs on the `people` table (already modeled), `podroll` is Stage 11, and
  // `txt` records are screen 16b's own flow — none of those three live here.
  description: text("description"),
  language: text("language").notNull().default("en"),
  explicit: integer("explicit").notNull().default(0),
  podcastTags: text("podcast_tags", { mode: "json" }),
  // The verified show-artwork asset (assets.kind "show_artwork"); null until one is uploaded.
  artworkAssetId: text("artwork_asset_id"),
  // Wide header image behind the public show page's hero (assets.kind "show_banner").
  bannerAssetId: text("banner_asset_id"),
  settings: text("settings", { mode: "json" }),
  theme: text("theme", { mode: "json" }),
  shortStyle: text("short_style", { mode: "json" }),
  createdAt: integer("created_at")
    .notNull()
    .default(sql`(unixepoch('now','subsec')*1000)`),
});

