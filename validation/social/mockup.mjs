// Browser check for the /studio/social mockup: sidebar link, tabs, counters, customize panels, saved settings.
import { launch, BASE, ok, failCount, sleep } from "../editor/lib.mjs";
const OUT = process.env.OUT || "/tmp";
const { b, p, errs } = await launch();
await p.evaluate(() => localStorage.removeItem("podstudio.social.settings.v3"));
await p.click('[data-testid=nav-social]'); await p.waitForURL("**/studio/social"); await p.waitForSelector("text=Rewrite all");
ok("sidebar link opens Social", p.url().endsWith("/studio/social"));
ok("posts render", await p.locator('textarea[aria-label="Bluesky post"]').count() === 1);
const before = await p.locator('textarea[aria-label="Facebook post"]').inputValue();
await p.getByRole("radio", { name: "Short" }).click(); await sleep(200);
const after = await p.locator('textarea[aria-label="Facebook post"]').inputValue();
ok("length setting changes drafts", after.length < before.length, `${before.length} -> ${after.length}`);
await p.getByRole("button", { name: "Emoji" }).or(p.getByRole("switch", { name: "Emoji" })).first().click(); await sleep(200);
ok("emoji switch applies", (await p.locator('textarea[aria-label="Facebook post"]').inputValue()).includes("🎙️"));
await p.screenshot({ path: OUT + "/social-posts.png", fullPage: true });
await p.reload(); await p.waitForSelector("text=Rewrite all"); await sleep(400);
ok("settings persist across reload", (await p.locator('textarea[aria-label="Facebook post"]').inputValue()).includes("🎙️"));
await p.getByRole("tab", { name: "Graphics" }).click(); await sleep(800);
ok("TWP fonts loaded", await p.evaluate(() => document.fonts.check('500 20px Archivo') && document.fonts.check('700 20px "JetBrains Mono"')));
ok("graphics drawn on canvas", await p.locator('canvas[aria-label="Instagram post preview"]').count() === 1);
await p.screenshot({ path: OUT + "/social-graphics.png", fullPage: true });
await p.getByRole("radio", { name: "Quote" }).click(); await sleep(300);
await p.screenshot({ path: OUT + "/social-graphics-quote.png", fullPage: true });
await p.getByRole("radio", { name: "Headline" }).click();
// Wordmark & fonts sheet
await p.getByRole("button", { name: "Wordmark & fonts" }).click(); await sleep(500);
ok("wordmark sheet opens with preview", await p.locator('canvas[aria-label="Wordmark preview"]').count() === 1);
const auto = await p.locator('textarea[aria-label="Stacked name"]').inputValue();
ok("stacked name follows the show title", auto.split("\n").length >= 1, JSON.stringify(auto));
await p.locator('textarea[aria-label="Stacked name"]').fill("MIC DROP\nRADIO");
await p.getByRole("combobox", { name: "Headline font" }).click(); await p.getByRole("option", { name: "Oswald" }).click(); await sleep(400);
await p.screenshot({ path: OUT + "/social-brand-text.png" });
await p.locator('input[type=file][accept^="image/png"]').setInputFiles(process.env.LOGO || "test-logo.svg"); await sleep(600);
await p.getByRole("radio", { name: "White" }).click(); await sleep(300);
await p.screenshot({ path: OUT + "/social-brand-logo.png" });
await p.locator('input[type=file][accept^=".woff2"]').first().setInputFiles(process.env.FONT || "font.woff2"); await sleep(800);
ok("custom font added", await p.locator("text=My Brand Font added").count() > 0);
await p.getByRole("button", { name: "Done" }).click(); await sleep(300);
await p.screenshot({ path: OUT + "/social-graphics-logo.png", fullPage: true });
await p.evaluate(() => localStorage.removeItem("podstudio.social.assets.v1"));
await p.getByRole("tab", { name: "Carousel" }).click(); await sleep(500);
await p.screenshot({ path: OUT + "/social-carousel.png", fullPage: true });
await p.getByRole("tab", { name: "Reels" }).click(); await sleep(500);
await p.screenshot({ path: OUT + "/social-reels-rest.png", fullPage: true });
await p.locator('input[type=file][accept="audio/*"]').setInputFiles(process.env.CLIP || "test-clip.wav");
await p.waitForSelector("text=test-clip.wav", { timeout: 15000 });
ok("audio file analysed", true);
await p.getByRole("button", { name: "Play preview" }).first().click(); await sleep(1600);
ok("reel plays with audio", await p.locator("text=/0:0[1-9] \\/ 0:08/").count() > 0);
await p.screenshot({ path: OUT + "/social-reels.png", fullPage: true });
await p.getByRole("button", { name: "Pause preview" }).first().click();
await p.getByRole("switch", { name: "Show safe zones" }).click(); await sleep(200);
await p.locator('canvas[aria-label="Reel preview, clip 1"]').screenshot({ path: OUT + "/social-reel-safe.png" });
await p.getByRole("switch", { name: "Show safe zones" }).click();
await p.getByRole("button", { name: "Show voice" }).click(); await sleep(400);
ok("voice sheet opens", await p.locator('textarea[aria-label="Voice"]').count() === 1);
await p.keyboard.press("Escape");
await p.setViewportSize({ width: 390, height: 844 }); await p.getByRole("tab", { name: "Posts" }).click(); await sleep(400);
const sw = await p.evaluate(() => document.documentElement.scrollWidth);
ok("no horizontal scroll at 390", sw <= 390, String(sw));
await p.screenshot({ path: OUT + "/social-phone.png", fullPage: true });
await p.evaluate(() => localStorage.removeItem("podstudio.social.settings.v3"));
ok("no page errors", errs.length === 0, errs.join(" | "));
await b.close(); process.exit(failCount() ? 1 : 0);
