import { launch, BASE, sleep, ok, failCount, resetProject, clearImports } from "./lib.mjs";
import fs from "fs";
import { execSync } from "child_process";
const epId = fs.readFileSync(new URL("./epid.txt", import.meta.url), "utf8").trim();
const { b, ctx, p, errs } = await launch();
resetProject(epId); await clearImports(ctx, epId);
await p.goto(BASE + "/studio/editor?episode=" + epId); await p.click("[data-testid=start-editing]"); await p.waitForSelector("[data-testid=canvas-host]"); await sleep(800);
await p.click("[data-testid=open-export]"); await p.waitForSelector("[data-testid=export-dialog]"); await p.click("[data-testid=fmt-wav]");
ok("mono target shown", (await p.innerText("[data-testid=export-target]")).includes("−19 LUFS") || (await p.innerText("[data-testid=export-target]")).includes("-19 LUFS"), await p.innerText("[data-testid=export-target]"));
const runOne = async (stereo) => {
  if (stereo) await p.click("[data-testid=ch-stereo]"); else await p.click("[data-testid=ch-mono]");
  await p.click("[data-testid=bd-24]"); await p.click("[data-testid=sr-48]");
  const before = await p.locator("[data-testid=export-job]").count();
  await p.click("[data-testid=start-export]");
  await p.waitForFunction((n) => document.querySelectorAll("[data-testid=export-job]").length > n && document.querySelector("[data-testid=export-job]").dataset.status === "verified", before, { timeout: 180000 });
  const row = p.locator("[data-testid=export-job]").first();
  const text = await row.innerText();
  const href = await row.locator("[data-testid=export-download]").getAttribute("href");
  const buf = Buffer.from(await (await ctx.request.get(BASE + href)).body());
  const f = `export-${stereo ? "stereo" : "mono"}.wav`; fs.writeFileSync(f, buf);
  const r = execSync(`ffmpeg -hide_banner -nostats -i ${f} -af ebur128=peak=true -f null - 2>&1 | sed -n '/Summary/,$p'`).toString();
  const I = +r.match(/I:\s+(-?[\d.]+) LUFS/)[1], TP = +r.match(/Peak:\s+(-?[\d.]+) dBFS/)[1];
  const ch = buf.readUInt16LE(22);
  return { text, I, TP, ch };
};
const mono = await runOne(false);
console.log("mono:", mono.text.replace(/\n/g, " | "), "ffmpeg I", mono.I, "TP", mono.TP);
ok("mono file: 1 channel", mono.ch === 1);
ok("mono file measures −19 LUFS ±0.5 (ffmpeg ebur128)", Math.abs(mono.I + 19) <= 0.5, String(mono.I));
ok("mono true peak ≤ −1 dBTP (ffmpeg)", mono.TP <= -1.0 + 0.05, String(mono.TP));
const st = await runOne(true);
console.log("stereo:", st.text.replace(/\n/g, " | "), "ffmpeg I", st.I, "TP", st.TP);
ok("stereo file: 2 channels", st.ch === 2);
ok("stereo file measures −16 LUFS ±0.5 (ffmpeg ebur128)", Math.abs(st.I + 16) <= 0.5, String(st.I));
ok("stereo true peak ≤ −1 dBTP (ffmpeg)", st.TP <= -1.0 + 0.05, String(st.TP));
await p.locator("[data-testid=export-dialog] > div").screenshot({ path: "export-panel.png" });
// clean up the exports
for (const id of await p.$$eval("[data-testid=export-job] [data-testid=export-download]", (a) => a.map((x) => x.getAttribute("href").split("/").pop()))) await ctx.request.delete(BASE + "/studio/exports/" + id);
resetProject(epId);
console.log("errors", errs); console.log("FAILS", failCount()); await b.close();
