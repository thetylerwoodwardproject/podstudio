// Playback with a per-track ducking rule active (switched on in the music track's FX popover) advances without errors.
import { launch, BASE, sleep, ok, failCount, resetProject, clearImports } from "./lib.mjs";
import fs from "fs";
const epId = fs.readFileSync(new URL("./epid.txt", import.meta.url), "utf8").trim();
const { b, ctx, p, errs } = await launch();
const proj = async () => await (await ctx.request.get(BASE + "/studio/projects/" + epId)).json();
const saved = async () => { await sleep(500); await p.waitForFunction(() => /^Saved/.test(document.querySelector("[data-testid=save-status]")?.textContent ?? ""), null, { timeout: 20000 }); };
resetProject(epId); await clearImports(ctx, epId);
await p.goto(BASE + "/studio/editor?episode=" + epId); await p.click("[data-testid=start-editing]"); await p.waitForSelector("[data-testid=canvas-host]"); await sleep(800);
await p.click("[data-testid=add-track]"); await p.click("[data-testid=add-track-music]"); await saved();
await p.locator("[data-testid=track-music] [data-testid=track-fx-button]").click();
await p.waitForSelector("[data-testid=fx-popover] [data-testid=fx-chain]");
await p.click("[data-testid=fx-popover] [data-testid=fx-duck-on]"); await saved();
ok("ducking rule created for the music track", (await proj()).doc.ducking?.some((r) => r.enabled));
await p.screenshot({ path: "duck-fx.png" });
await p.keyboard.press("Escape"); await sleep(200);
await p.keyboard.press("Home"); await p.click("[data-testid=play]"); await sleep(5000);
const clk = await p.innerText("[data-testid=clock]"); await p.keyboard.press("Space");
ok("playback with ducking active advances and raises no errors", !clk.startsWith("0:00.0") && errs.length === 0, clk.replace(/\n/g, " ") + " " + JSON.stringify(errs));
resetProject(epId);
console.log("FAILS", failCount()); await b.close();
